// references (Guyton, Robbins, Harrison's principles — restated simply).

export interface Layer3D {
  id: string
  label: string
  emoji: string
  /** depth position 0 (front) .. 6 (back) — rendered as translateZ offsets */
  z: number
  /** one-line simple explanation (shown when the layer is selected) */
  simple: string
  /** 1–2 line exam-grade detail */
  detail: string
  tint?: string // optional accent color (any CSS color)
  /** can this layer be highlighted in isolation mode (dims the rest)? default true */
  isolateable?: boolean
  /** what happens clinically when this structure fails */
  clinicalNote?: string
  /** the exam angle on this structure */
  examNote?: string
  /** one line used by guided step-by-step mode */
  stepHint?: string
}

/** One station of a guided, step-by-step walk through the diagram */
export interface GuidedStep {
  title: string
  detail: string
  /** layer to highlight while this step is shown */
  layerId?: string
}

export interface NormalVsAbnormal {
  normal: string
  abnormal: string
}

export interface QuizItem {
  q: string
  options: string[]
  answerIndex: number
  explain: string
}

export interface Diagram3D {
  conceptId: string
  title: string
  emoji: string
  /** plain-language intro shown above the stage */
  intro: string
  layers: Layer3D[]
  /** real-world anchor line shown under the stage */
  clinical: string
  /** 3–6 station guided tour (viewer shows a step strip when present) */
  guidedSteps?: GuidedStep[]
  /** deeper clinical story shown as a card under the canvas */
  clinicalCorrelation?: string
  /** compact two-column normal vs abnormal compare */
  normalVsAbnormal?: NormalVsAbnormal
  /** 2–3 inline self-test items ("Test me on this") */
  quiz?: QuizItem[]
}

